import { defineConfig } from 'astro/config';

// i18n (specs.md §7.2): deliberately NOT using Astro's built-in `i18n`
// config. Its 'automatic' mode expects real per-locale folders under
// src/pages/<locale>/ (this project's routes are generated dynamically from
// content-collection entity ids, not fixed folders); its 'manual' mode
// requires an SSR middleware file, which is an `output: 'server'`/adapter
// concept that doesn't apply to this fully static, no-adapter build (Astro
// throws MissingMiddlewareForInternationalization if `routing: 'manual'` is
// set without one). The locale-prefixed-URL behaviour the spec wants
// (`/es/...`, `/en/...`, symmetric including the default) is achieved
// directly instead: a plain `[locale]` dynamic route param, generated by
// each page's own `getStaticPaths` from src/i18n/locales.ts (the single open
// list, rule A9) — see src/pages/[locale]/entity/[id].astro. hreflang
// alternates and the language switcher (§7.2) are built by hand in Phase 4
// from that same list, not from `astro:i18n` helpers.
export default defineConfig({
  output: 'static',
  vite: {
    server: {
      // Allows the Vite dev server to be reached via a Tailscale hostname
      // (or any other non-localhost name) instead of only localhost/127.0.0.1.
      // '.ts.net' covers any Tailscale MagicDNS host, not just this machine's.
      allowedHosts: ['lenovo-do-alvaro.siren-armadillo.ts.net', '.ts.net'],
    },
  },
});
